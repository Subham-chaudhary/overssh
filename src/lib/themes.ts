// Compact builder for the dark themes added later: same token set and
// structure as the hand-written Monaco themes above, driven by a palette.
interface DarkPalette {
  bg: string;
  fg: string;
  /** Darker chrome: gutter, minimap, widgets. */
  panel: string;
  /** Selection / line-highlight base and borders. */
  sel: string;
  /** Line numbers, whitespace and indent-guide accent. */
  dim: string;
  cursor: string;
  bracket: string;
  comment: string;
  keyword: string;
  string: string;
  number: string;
  regexp: string;
  type: string;
  fn: string;
  constant: string;
  operator: string;
  tag: string;
  attr: string;
  annotation: string;
  invalid: string;
}

function darkMonaco(p: DarkPalette): MonacoThemeData {
  return {
    base: 'vs-dark',
    inherit: true,
    rules: [
      { token: 'comment', foreground: p.comment, fontStyle: 'italic' },
      { token: 'keyword', foreground: p.keyword },
      { token: 'string', foreground: p.string },
      { token: 'number', foreground: p.number },
      { token: 'regexp', foreground: p.regexp },
      { token: 'type', foreground: p.type },
      { token: 'class', foreground: p.type },
      { token: 'function', foreground: p.fn },
      { token: 'variable', foreground: p.fg },
      { token: 'variable.predefined', foreground: p.keyword },
      { token: 'constant', foreground: p.constant },
      { token: 'operator', foreground: p.operator },
      { token: 'delimiter', foreground: p.fg },
      { token: 'tag', foreground: p.tag },
      { token: 'attribute.name', foreground: p.attr },
      { token: 'attribute.value', foreground: p.string },
      { token: 'key', foreground: p.fn },
      { token: 'string.key.json', foreground: p.fn },
      { token: 'string.value.json', foreground: p.string },
      { token: 'metatag', foreground: p.tag },
      { token: 'annotation', foreground: p.annotation },
      { token: 'invalid', foreground: p.invalid, background: p.sel },
    ],
    colors: {
      'editor.background': `#${p.bg}`,
      'editor.foreground': `#${p.fg}`,
      'editorLineNumber.foreground': `#${p.dim}`,
      'editorLineNumber.activeForeground': `#${p.fg}`,
      'editor.selectionBackground': `#${p.sel}`,
      'editor.inactiveSelectionBackground': `#${p.sel}`,
      'editor.lineHighlightBackground': `#${p.sel}66`,
      'editorCursor.foreground': `#${p.cursor}`,
      'editorWhitespace.foreground': `#${p.sel}`,
      'editorIndentGuide.background1': `#${p.sel}`,
      'editorIndentGuide.activeBackground1': `#${p.dim}`,
      'editorBracketMatch.background': `#${p.bracket}33`,
      'editorBracketMatch.border': `#${p.bracket}`,
      'minimap.background': `#${p.panel}`,
      'editorGutter.background': `#${p.panel}`,
      'editorWidget.background': `#${p.panel}`,
      'editorWidget.border': `#${p.sel}`,
      'editorSuggestWidget.background': `#${p.panel}`,
      'editorSuggestWidget.selectedBackground': `#${p.sel}`,
      'scrollbarSlider.background': `#${p.sel}80`,
      'scrollbarSlider.hoverBackground': `#${p.sel}`,
      'editorStickyScroll.background': `#${p.bg}`,
    },
  };
}

