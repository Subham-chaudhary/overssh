export type ThemeId =
  | 'one-dark'
  | 'dracula'
  | 'tokyo-night'
  | 'catppuccin-mocha'
  | 'github-light'
  | 'github-dark'
  | 'nord'
  | 'rose-pine'
  | 'gruvbox-dark'
  | 'kanagawa';

// Minimal Monaco theme type definition (monaco-editor may not be installed yet)
export interface MonacoThemeData {
  base: 'vs' | 'vs-dark';
  inherit: boolean;
  rules: Array<{
    token: string;
    foreground?: string;
    fontStyle?: string;
    background?: string;
  }>;
  colors: Record<string, string>;
}

export interface ThemeDef {
  id: ThemeId;
  label: string;
  isDark: boolean;
  /** The theme's own `--primary` (what "Theme default" means in the accent picker). */
  accent: string;
  monaco: MonacoThemeData;
  xterm: ITheme;
}

